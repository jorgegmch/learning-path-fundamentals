
# CALCULADORA DE PROMEDIO DE CUATRO NÚMEROS

num1=float(input("Ingrese el valor del primer número: "))
num2=float(input("Ingrese el valor del segundo número: "))
num3=float(input("Ingrese el valor del tercer número: "))
num4=float(input("Ingrese el valor del cuarto número: "))

multiplicacion=num1*num2*num3*num4
suma=num1+num2+num3+num4
promedio=(num1+num2+num3+num4)/4

print(f"El producto de los 4 números es igual a: {multiplicacion}, su suma es: {suma} y su media aritmetica: {promedio}")